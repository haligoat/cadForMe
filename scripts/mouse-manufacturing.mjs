// Writes the manufacturing package for the laptop mouse: STEP + STL + SVG drawing per made part, and a BOM.
import fs from "node:fs";
import path from "node:path";
import { initKernel } from "../test/helpers.mjs";
import { initSolver } from "../src/kernel/sketch2.js";
import { buildPart, collectParts, measure, exportSTEP, exportSTL, makeDrawing } from "../src/kernel/geometry.js";

const dir = process.argv[2] ?? "examples/laptop-mouse";
await initKernel(); await initSolver(fs.readFileSync("node_modules/@salusoft89/planegcs/dist/planegcs_dist/planegcs.wasm"));
const files = Object.fromEntries(fs.readdirSync(`${dir}/parts`).map((f) => [`parts/${f}`, fs.readFileSync(`${dir}/parts/${f}`, "utf8")]));
const outDir = path.join(dir, "manufacturing"); fs.mkdirSync(outDir, { recursive: true });

const MADE = [
  ["top-shell", "Top shell", "Injection moulded", "ABS (or PC/ABS)", 1],
  ["bottom-shell", "Bottom shell", "Injection moulded", "ABS", 1],
  ["battery-door", "Battery door", "Injection moulded", "ABS", 1],
  ["wheel-bracket", "Wheel bracket", "Injection moulded", "POM (acetal)", 1],
  ["scroll-wheel", "Scroll wheel", "Injection moulded, TPE overmould", "PC + TPE", 1],
];
const rows = [];
for (const [slug, label, process_, material, qty] of MADE) {
  const part = JSON.parse(files[`parts/${slug}.part.json`]);
  const r = buildPart(part, { parts: collectParts(part, files) });
  if (Object.keys(r.errors).length) throw new Error(`${slug}: ${JSON.stringify(r.errors)}`);
  const m = measure(r.bodies, part.material?.density ?? 1.05);
  fs.writeFileSync(path.join(outDir, `${slug}.step`), Buffer.from(await exportSTEP(r.bodies).arrayBuffer()));
  fs.writeFileSync(path.join(outDir, `${slug}.stl`), Buffer.from(await exportSTL(r.bodies).arrayBuffer()));
  fs.writeFileSync(path.join(outDir, `${slug}-drawing.svg`), makeDrawing(r.bodies, { name: label, material, mass: m.reduce((a, x) => a + x.mass, 0) }));
  rows.push(`| ${label} | ${qty} | ${process_} | ${material} | ${m.map((x) => x.size.map((v) => v.toFixed(1)).join(" × ")).join(", ")} | ${m.reduce((a, x) => a + x.mass, 0).toFixed(1)} g | \`${slug}.step\` |`);
  r.bodies.forEach((b) => b.delete());
}
const bom = `# Laptop mouse: bill of materials

Generated by cadSlop from the part files (run \`node scripts/mouse-manufacturing.mjs\`). Units mm.

## Made parts
| Part | Qty | Process | Material | Size | Mass | CAD |
|---|---|---|---|---|---|---|
${rows.join("\n")}

## Bought parts
| Part | Qty | Spec |
|---|---|---|
| Screw | 2 | M3 × 8, self-tapping for plastic (PT/Delta-PT style), pan or socket head |
| Wheel axle | 1 | Ø2 × 11 mm steel dowel pin |
| Click switch | 2 | Omron D2FC-F-7N (12.8 × 5.8 × 6.5 mm) or equivalent |
| Optical sensor + lens | 1 | Low-power optical mouse sensor module with clip-on lens |
| Scroll encoder | 1 | Mechanical mouse encoder, 11 mm height (mounts on the board under the wheel) |
| Main board | 1 | 1.6 mm FR-4, oval 31 × 38 mm, two Ø2.2 locating holes |
| Battery | 1 | AA (LR6), with spring + flat contacts |
| Glide feet | 3 | 0.6 mm PTFE pads, die-cut to the foot outlines |

## Design checks (all automated)
- Every part builds without errors; the assembly has 14 bodies.
- Interference check: no unintended overlaps between any two parts. The only overlaps are the screws cutting threads into the Ø2.5 pilot holes.
- Clearances: locating lip 0.2 mm, battery door 0.2 mm all round, wheel-to-bracket 0.3 mm, board locating pins 0.1 mm, snap-hook arm 0.4 mm behind the ledge.
- Snap fit: 0.4 mm barb engagement under the ledges, hooks 1 mm thick × 5.5 mm long (flex inwards to assemble).
- Buttons: flexures hinged at x = 8 mm, 0.8 mm separation slots, plungers with 0.3 mm pre-travel to the switches.

## Before tooling (needs a moulding engineer)
- Add 1° draft to vertical walls and the bosses (not modelled).
- Add internal ribs from the bosses to the walls, and fillets where walls meet.
- Confirm wall thickness (1.6 mm) and boss proportions (Ø6 boss, Ø2.5 pilot) with the moulder for the chosen resin.
- Tune button feel: the hinge stiffness depends on resin and the slot length.
`;
fs.writeFileSync(path.join(outDir, "BOM.md"), bom);
console.log(`wrote ${fs.readdirSync(outDir).length} files to ${outDir}`);
